# Merging dictionaries using | operator


dict1 = {"a": 1, "b": 2}; dict1_a=dict1['a']; dict1_b=dict1['b']
dict2 = {"c": 3, "d": 4}; dict2_c=dict2['c']; dict2_d=dict2['d']
merged_dict = dict1 | dict2; merged_dict_a=merged_dict['a']; merged_dict_b=merged_dict['b']; merged_dict_c=merged_dict['c']; merged_dict_d=merged_dict['d']
